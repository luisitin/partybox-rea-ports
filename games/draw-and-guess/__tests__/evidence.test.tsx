const writing = process.env['WRITE_EVIDENCE'] === '1';

/** Fixtures form one real match; done is the last reveal continued without any new answers. */
function makeFixtures(): Record<string, State> {
  let s = game.init({
    players: testPlayers(8, { bots: 8 }),
    settings: { laps: 1, drawSeconds: 30, difficulty: 'easy' },
    seed: 44,
    now: T0,
  });
  const fixtures: Record<string, State> = { choose: s };
  while (s.phase.id !== 'done') {
    if (s.phase.id === 'choose') {
      s = kit.input(s, s.drawer, { type: 'choose', index: 0 }, s.phase.startedAt + 1000);
      for (const [index, stroke] of (BOT_ART[s.word] ?? []).entries()) {
        s = kit.input(s, s.drawer, { type: 'stroke', stroke }, s.began + 100 + index * 10);
      }
      if (!fixtures.draw) fixtures.draw = s;
      let i = 0;
      for (const id of s.order.filter((id) => id !== s.drawer)) {
        if (i++ >= 3) break;
        s = kit.input(s, id, { type: 'guess', text: s.word }, s.began + 5000 + i * 1500);
      }
    } else if (s.phase.id === 'draw') s = kit.finish(s, 40);
    else if (s.phase.id === 'reveal') {
      fixtures.reveal ??= s;
      fixtures['reveal-last'] = s;
      s = kit.timer(s);
    }
  }
  fixtures.done = s;
  return fixtures;
}

const fixtures = makeFixtures();
type Surface = 'tv' | 'phone' | 'phone-only' | 'spectator' | 'artist';

function render(state: State, surface: Surface): string {
  const phoneOnly = surface === 'phone-only' || surface === 'spectator';
  const s = { ...state, phoneOnly };
  const id =
    surface === 'spectator'
      ? 'a-spectator'
      : surface === 'artist'
        ? s.drawer
        : s.order.find((id) => id !== s.drawer)!;
  const clock = s.phase.id === 'draw' ? s.clock : s.phase.startedAt;
  const view = { ...game.controllerView(s, id), vip: null };
  const me = s.players[id] ?? { id, name: 'Spectator', avatarId: 'fox', connected: true };
  return renderToStaticMarkup(
    <ServerClockProvider offsetMs={clock - Date.now()}>
      <PhoneOnlyProvider value={phoneOnly}>
        {surface === 'tv' ? (
          <Tv view={{ ...game.tvView(s), vip: null }} />
        ) : (
          <Controller view={view} me={me} send={() => undefined} />
        )}
      </PhoneOnlyProvider>
    </ServerClockProvider>,
  );
}

function cssFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? cssFiles(full) : name.endsWith('.css') ? [full] : [];
  });
}

const cssSources = await Promise.all(
  [
    ...cssFiles(join(root, 'games/draw-and-guess/client')),
    join(root, 'packages/game-sdk/src/tv/Stage.module.css'),
  ].map(async (file) => {
    const mod = (await import(pathToFileURL(file).href)) as { default?: Record<string, string> };
    return { text: readFileSync(file, 'utf8'), classes: mod.default ?? {} };
  }),
);
const tokens = readFileSync(join(root, 'design/tokens.css'), 'utf8');

/** SSR class names are generated by Vite; carry their CSS into standalone review files. */
function stylesFor(): string {
  return cssSources
    .map(({ text, classes }) =>
      text
        .replace(/\.([a-zA-Z_][\w-]*)/g, (match, name: string) => {
          const scoped = classes[name];
          return typeof scoped === 'string' ? `.${scoped}` : match;
        })
        .replace(/:global\(([^)]+)\)/g, '$1'),
    )
    .join('\n');
}

function document(
  markup: string,
  surface: Surface,
  title: string,
  heightOverride?: number,
): string {
  const tv = surface === 'tv';
  const width = tv ? 1920 : 390;
  const height = heightOverride ?? (tv ? 1080 : 844);
  return `<!doctype html>\n<html lang="en" data-surface="${tv ? 'tv' : 'controller'}" data-motion="off"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${title}</title><style>\n${tokens}\n${stylesFor()}\n*{box-sizing:border-box}html,body{margin:0;width:${width}px;height:${height}px;background:var(--pb-bg);color:var(--pb-text);font-family:var(--pb-font-family)}body{overflow:hidden}main{width:100%;height:100%;min-height:0}button,input{font:inherit}h1,h2,p{margin-top:0}\n</style></head><body><main>${markup}</main></body></html>\n`.replace(
    /[ \t]+$/gm,
    '',
  );
}

describe('review evidence and every phone phase', () => {
  it('fixtures cover each phase and done is the final reveal continued', () => {
    expect(Object.keys(fixtures)).toEqual(['choose', 'draw', 'reveal', 'reveal-last', 'done']);
    for (const phase of game.phases) expect(fixtures[phase]?.phase.id).toBe(phase);
    expect(kit.timer(fixtures['reveal-last']!)).toEqual(fixtures.done);
    expect(game.results(fixtures.done!)).not.toBeNull();
    if (writing) {
      mkdirSync(fixtureDir, { recursive: true });
      for (const [name, state] of Object.entries(fixtures))
        writeFileSync(
          join(fixtureDir, `${name}.json`),
          `${JSON.stringify(state, null, 2)}\n`,
          'utf8',
        );
    }
  });

  it.each(Object.entries(fixtures))(
    'renders %s on every surface, with a stage for spectators and phone-only rooms',
    (phase, state) => {
      if (writing) mkdirSync(mediaDir, { recursive: true });
      for (const surface of ['tv', 'phone', 'phone-only', 'spectator', 'artist'] as const) {
        const html = render(state, surface);
        expect(html.length).toBeGreaterThan(100);
        if (surface === 'phone-only' || surface === 'spectator') {
          expect(html).toContain('aria-label="Live drawing"');
          expect(html).not.toMatch(/Look at the TV|on the TV|Watch the TV/);
        }
        if (surface === 'spectator') {
          expect(html).not.toContain('<input');
          expect(html).not.toContain('<button');
          expect(html).not.toContain('<canvas');
        }
        if ((phase === 'choose' || phase === 'draw') && surface !== 'artist') {
          for (const secret of [state.word, ...state.choices].filter(Boolean))
            expect(html).not.toContain(secret);
        }
        if ((phase === 'reveal' || phase === 'reveal-last') && state.word)
          expect(html).toContain(state.word);
        if (writing)
          writeFileSync(
            join(mediaDir, `${phase}-${surface}.html`),
            document(html, surface, `${phase} / ${surface}`),
            'utf8',
          );
      }
    },
  );

  it('shows the artist real solver progress and gives a solver an immediate private point receipt', () => {
    const s = fixtures.draw!;
    const id = s.order.find((playerId) => playerId !== s.drawer)!;
    expect(render(s, 'artist')).toContain('0/7 guessed it');
    const solved = kit.input(s, id, { type: 'guess', text: s.word }, s.began + 6000);
    const artist = render(solved, 'artist');
    const phone = render(solved, 'phone');
    expect(artist).toContain('1/7 guessed it');
    expect(phone).toContain('Correct! +860 points');
    expect(phone).not.toContain('<input');
    expect(phone).not.toContain(s.word);
    expect(game.controllerView(solved, id).myPoints).toBe(860);
    if (writing) {
      mkdirSync(mediaDir, { recursive: true });
      writeFileSync(
        join(mediaDir, 'draw-artist-progress.html'),
        document(artist, 'artist', 'Artist / one solver'),
        'utf8',
      );
      writeFileSync(
        join(mediaDir, 'draw-phone-solved.html'),
        document(phone, 'phone', 'Solver / earned points'),
        'utf8',
      );
    }
  });

  it('shows the next artist only during reveal and prepares that seat on every stage', () => {
    const reveal = fixtures.reveal!;
    const name = game.tvView(reveal).nextArtistName;
    expect(name).toBeTruthy();
    for (const surface of ['tv', 'phone', 'phone-only', 'spectator', 'artist'] as const) {
      const html = render(reveal, surface);
      expect(html).toContain(`Next artist: ${name}`);
      expect(render(fixtures.done!, surface)).not.toContain('Next artist:');
    }
  });

  it('renders the longest word, long names and an eight-way tie for fit review', () => {
    const long: State = {
      ...fixtures.draw!,
      word: 'pedestrian crossing',
      hintCount: 0,
      players: Object.fromEntries(
        Object.entries(fixtures.draw!.players).map(([id, player], i) => [
          id,
          { ...player, name: `AlexandriaPlayer${i + 1}` },
        ]),
      ),
    };
    const tie: State = {
      ...fixtures.done!,
      players: long.players,
      scores: Object.fromEntries(Object.keys(fixtures.done!.players).map((id) => [id, 500])),
    };
    expect(render(long, 'phone-only')).toContain('_ _ _ _');
    expect(render(tie, 'phone-only').match(/Joint winner, place 1/g) ?? []).toHaveLength(8);
    if (writing) {
      for (const surface of ['tv', 'phone-only'] as const) {
        writeFileSync(
          join(mediaDir, `done-tie-${surface}.html`),
          document(render(tie, surface), surface, `Eight tied winners / ${surface}`),
          'utf8',
        );
        writeFileSync(
          join(mediaDir, `draw-long-${surface}.html`),
          document(render(long, surface), surface, `Longest word / ${surface}`),
          'utf8',
        );
      }
      writeFileSync(
        join(mediaDir, 'draw-long-keyboard.html'),
        document(render(long, 'phone-only'), 'phone-only', 'Longest word / keyboard', 500),
        'utf8',
      );
      writeFileSync(
        join(mediaDir, 'draw-artist-keyboard.html'),
        document(render(long, 'artist'), 'artist', 'Artist / compact screen', 500),
        'utf8',
      );
    }
  });

  it('records hashes and keeps all evidence below the job 10 MB limit', () => {
    if (!writing) return;
    const media = readdirSync(mediaDir)
      .filter((name) => !name.startsWith('.'))
      .sort();
    const bytes = media.reduce((n, name) => n + statSync(join(mediaDir, name)).size, 0);
    expect(bytes).toBeLessThan(10 * 1024 * 1024);
    const hashes = media
      .map(
        (name) =>
          `${createHash('sha256')
            .update(readFileSync(join(mediaDir, name)))
            .digest('hex')}  media/${name}`,
      )
      .join('\n');
    writeFileSync(join(jobDir, 'SHA256SUMS.txt'), `${hashes}\n`, 'utf8');
    console.log(`EVIDENCE ${media.length} files, ${bytes} bytes`);
  });
});
